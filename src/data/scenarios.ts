export function normalizeTestQuestion(q: TestQuestion | string): TestQuestion {
  if (typeof q === 'string') {
    return {
      task: q,
      hint: 'Сформулируйте сообщение своими словами от первого лица, опираясь на эту цель.',
      sampleQuery: q,
    };
  }
  return q;
}

